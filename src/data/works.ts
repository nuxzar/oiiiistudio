export type WorkPhoto = {
  tone: string;
  src?: string;
};

export type Work = {
  slug: string;
  client: string;
  title: string;
  intro: string;
  summary: string;
  need: string;
  creative: string;
  outcome: string;
  color: string;
  accent: string;
  surface: "light" | "dark";
  photos: WorkPhoto[];
};

export const works: Work[] = drafts.map((draft) => {
  const { color, accent, surface } = lookFor(draft.id);
  const images =
    "images" in draft ? Array.from(draft.images as readonly string[]) : undefined;
  const photos: WorkPhoto[] =
    images && images.length > 0
      ? images.map((src) => ({ src, tone: color }))
      : [{ tone: color }, { tone: accent }, { tone: color }];

  return {
    slug: draft.id,
    client: draft.client,
    title: draft.title,
    intro: draft.intro,
    summary: draft.summary,
    need: draft.need,
    creative: draft.creative,
    outcome: draft.outcome,
    color,
    accent,
    surface,
    photos,
  };
});

export function getWork(slug: string) {
  return works.find((work) => work.slug === slug);
}

export function getNextWork(slug: string) {
  const index = works.findIndex((work) => work.slug === slug);
  if (index === -1) return works[0];
  return works[(index + 1) % works.length];
}
